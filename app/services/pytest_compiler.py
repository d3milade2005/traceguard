import ast
import hashlib
import json
from dataclasses import dataclass

from pydantic import BaseModel, ValidationError

from app.core.exceptions import (
    CompilationInputError,
    CompilationInvariantError,
    GeneratedSafetyError,
    GeneratedSyntaxError,
    InvalidScenarioSnapshotError,
    RegressionNotSynthesizableError,
    UnsupportedAssertionError,
    UnsupportedSpecVersionError,
)
from app.regression_runtime import HARNESS_ID, HARNESS_VERSION
from app.schemas.regression_specs import (
    Assertion,
    RegressionRecord,
    RegressionSpec,
    ScenarioSnapshot,
    check_data,
)

COMPILER_VERSION = "pytest-compiler-v1"
ARTIFACT_VERSION = "generated-test-v1"
SUPPORTED_SPEC_VERSION = "regression-spec-v1"
ASSERTION_HELPERS = {
    "equals": "assert_equals",
    "not_equals": "assert_not_equals",
    "contains": "assert_contains",
    "not_contains": "assert_not_contains",
    "exists": "assert_exists",
    "not_exists": "assert_not_exists",
}


@dataclass(frozen=True)
class CompiledTest:
    test_name: str
    source_code: str
    source_digest: str
    version: str = ARTIFACT_VERSION
    compiler_version: str = COMPILER_VERSION
    harness_identifier: str = HARNESS_ID
    harness_version: str = HARNESS_VERSION
    framework: str = "pytest"


@dataclass(frozen=True)
class RenderInput:
    test_name: str
    target_agent: str
    scenario_json: str
    assertions: tuple[Assertion, ...]


def canonical_json(value: object) -> str:
    return json.dumps(
        value, sort_keys=True, ensure_ascii=True, allow_nan=False, separators=(",", ":")
    )


def _contract_values(value: object, depth: int = 0) -> object:
    """Read raw model values before serializers can coerce an invalid union member."""
    if depth > 30:
        raise ValueError("Contract nesting exceeds the supported bound")
    if isinstance(value, BaseModel):
        if set(value.__dict__) - type(value).model_fields.keys() or value.__pydantic_extra__:
            raise ValueError("Unknown contract fields are unsupported")
        return {
            name: _contract_values(getattr(value, name), depth + 1)
            for name in type(value).model_fields
        }
    if isinstance(value, tuple):
        return tuple(_contract_values(child, depth + 1) for child in value)
    if isinstance(value, list):
        return [_contract_values(child, depth + 1) for child in value]
    if isinstance(value, dict):
        return {key: _contract_values(child, depth + 1) for key, child in value.items()}
    return value


def validate_compilation_input(
    record: RegressionRecord, *, max_scenario_bytes: int
) -> tuple[RegressionSpec, ScenarioSnapshot]:
    if record.status != "completed" or record.disposition != "synthesizable":
        raise RegressionNotSynthesizableError
    if record.spec is None:
        raise CompilationInputError
    if record.scenario_snapshot is None:
        raise InvalidScenarioSnapshotError
    if record.version != SUPPORTED_SPEC_VERSION or record.spec.version != SUPPORTED_SPEC_VERSION:
        raise UnsupportedSpecVersionError
    try:
        if any(assertion.kind not in ASSERTION_HELPERS for assertion in record.spec.assertions):
            raise UnsupportedAssertionError
        spec = RegressionSpec.model_validate(_contract_values(record.spec))
        try:
            snapshot = ScenarioSnapshot.model_validate(_contract_values(record.scenario_snapshot))
            check_data(snapshot.model_dump(mode="json"))
        except (ValidationError, ValueError, TypeError, AttributeError) as exc:
            raise InvalidScenarioSnapshotError from exc
        if (
            spec.disposition != "synthesizable"
            or spec.target_agent != record.target_agent
            or spec.title != record.title
            or record.review_reason is not None
            or spec.scenario is None
            or spec.scenario.stimulus.field not in {"input", "tool_arguments"}
            or spec.scenario.stimulus.path
        ):
            raise CompilationInputError
        if (
            snapshot.stimulus is None
            or len(snapshot.preconditions) != len(spec.scenario.preconditions)
            or len(snapshot.model_dump_json().encode("utf-8")) > max_scenario_bytes
        ):
            raise InvalidScenarioSnapshotError
    except (ValidationError, ValueError, TypeError, AttributeError) as exc:
        raise CompilationInputError from exc
    return spec, snapshot


def render_source(render: RenderInput) -> str:
    """Insert only serialized data and a validated identifier into a fixed source layout."""
    lines = [
        f"# Generated by {COMPILER_VERSION}. UNTRUSTED artifact; execute only in isolation.",
        "import json",
        "from app import regression_runtime as runtime",
        "",
        "",
        f"def {render.test_name}(regression_harness):",
        f"    scenario = json.loads({render.scenario_json!r})",
        "    harness = runtime.require_harness("
        f"regression_harness, {HARNESS_ID!r}, {HARNESS_VERSION!r})",
        "    observation = runtime.require_observation(",
        "        harness.invoke(",
        f"            target_agent={render.target_agent!r},",
        '            stimulus=scenario["stimulus"],',
        '            preconditions=tuple(scenario["preconditions"]),',
        "        )",
        "    )",
    ]
    for assertion in render.assertions:
        helper = ASSERTION_HELPERS.get(assertion.kind)
        if helper is None:
            raise CompilationInvariantError
        operands = f"observation.{assertion.observable}, {assertion.path!r}"
        if assertion.kind not in {"exists", "not_exists"}:
            operands += f", json.loads({canonical_json(assertion.expected)!r})"
        lines.append(f"    runtime.{helper}({operands})")
    return "\n".join(lines) + "\n"


APPROVED_NODES = (
    ast.Module,
    ast.Import,
    ast.ImportFrom,
    ast.alias,
    ast.FunctionDef,
    ast.arguments,
    ast.arg,
    ast.Assign,
    ast.Name,
    ast.Load,
    ast.Store,
    ast.Call,
    ast.Attribute,
    ast.Constant,
    ast.Tuple,
    ast.keyword,
    ast.Subscript,
    ast.Expr,
)
APPROVED_CALLS = {
    ("json", "loads"),
    ("harness", "invoke"),
    ("runtime", "require_harness"),
    ("runtime", "require_observation"),
    *(("runtime", name) for name in ASSERTION_HELPERS.values()),
}


def validate_source(
    source: str, *, expected_source: str, test_name: str, max_source_bytes: int
) -> None:
    """Parse and inspect source only; never compile, import, or execute the artifact."""
    if len(source.encode("utf-8")) > max_source_bytes:
        raise GeneratedSafetyError
    try:
        tree = ast.parse(source)
    except (SyntaxError, ValueError, RecursionError) as exc:
        raise GeneratedSyntaxError from exc
    imports = [node for node in ast.walk(tree) if isinstance(node, (ast.Import, ast.ImportFrom))]
    approved_imports = ast.parse(
        "import json\nfrom app import regression_runtime as runtime\n"
    ).body
    if [ast.dump(node) for node in imports] != [ast.dump(node) for node in approved_imports]:
        raise GeneratedSafetyError
    functions = [node for node in tree.body if isinstance(node, ast.FunctionDef)]
    if (
        len(tree.body) != 3
        or len(functions) != 1
        or functions[0].name != test_name
        or functions[0].decorator_list
        or [argument.arg for argument in functions[0].args.args] != ["regression_harness"]
    ):
        raise GeneratedSafetyError
    for node in ast.walk(tree):
        if not isinstance(node, APPROVED_NODES):
            raise GeneratedSafetyError
        if isinstance(node, ast.Attribute) and (
            not isinstance(node.value, ast.Name)
            or (node.value.id, node.attr)
            not in APPROVED_CALLS
            | {("observation", "output"), ("observation", "tool_result"), ("observation", "status")}
        ):
            raise GeneratedSafetyError
        if isinstance(node, ast.Call):
            target = node.func
            if isinstance(target, ast.Name) and target.id == "tuple":
                continue
            if (
                not isinstance(target, ast.Attribute)
                or not isinstance(target.value, ast.Name)
                or (target.value.id, target.attr) not in APPROVED_CALLS
            ):
                raise GeneratedSafetyError
    if source != expected_source:
        raise GeneratedSafetyError


class PytestCompiler:
    def __init__(self, *, max_source_bytes: int, max_scenario_bytes: int) -> None:
        self.max_source_bytes = max_source_bytes
        self.max_scenario_bytes = max_scenario_bytes

    def compile(self, record: RegressionRecord) -> CompiledTest:
        spec, snapshot = validate_compilation_input(
            record, max_scenario_bytes=self.max_scenario_bytes
        )
        assert spec.target_agent is not None
        render = RenderInput(
            spec.test_name,
            spec.target_agent,
            canonical_json(snapshot.model_dump(mode="json")),
            spec.assertions,
        )
        source = render_source(render)
        validate_source(
            source,
            expected_source=render_source(render),
            test_name=spec.test_name,
            max_source_bytes=self.max_source_bytes,
        )
        return CompiledTest(
            test_name=spec.test_name,
            source_code=source,
            source_digest=hashlib.sha256(source.encode("utf-8")).hexdigest(),
        )
